"""
Content model for database persistence.

Defines the Content table with SQLAlchemy ORM for storing uploaded file metadata,
structured document summaries, section-level breakdowns, and learning intelligence.
"""
import uuid
import json
from datetime import datetime
from typing import Optional, List

from app.database import db


class Content(db.Model):
    """Content model representing uploaded files and their structured learning intelligence."""
    
    __tablename__ = 'contents'
    
    id = db.Column(db.String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    user_id = db.Column(db.String(36), db.ForeignKey('users.id'), nullable=False)
    filename = db.Column(db.String(255), nullable=False)
    content_type = db.Column(db.String(50), nullable=False)
    file_path = db.Column(db.String(500), nullable=False)
    file_size = db.Column(db.Integer, default=0)
    file_data = db.Column(db.LargeBinary, nullable=True)  # Raw file bytes for persistent viewing
    title = db.Column(db.String(255), nullable=True)
    summary = db.Column(db.Text, nullable=True)
    extracted_text = db.Column(db.Text, nullable=True)  # Full extracted text from PDF/video/DOCX/PPTX/TXT
    key_points_json = db.Column(db.Text, nullable=True)  # JSON array
    topics_json = db.Column(db.Text, nullable=True)  # JSON array
    processing_status = db.Column(db.String(20), default='pending')
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    
    # Structured Document Summary fields (generated by ContentAgent)
    document_summary_json = db.Column(db.Text, nullable=True)  # Full structured summary from ContentAgent
    sections_json = db.Column(db.Text, nullable=True)  # Section-level breakdown for citation mapping
    learning_objectives_json = db.Column(db.Text, nullable=True)  # Learning objectives
    discussion_topics_json = db.Column(db.Text, nullable=True)  # Discussion topics
    important_terms_json = db.Column(db.Text, nullable=True)  # Vocabulary/terms
    faq_json = db.Column(db.Text, nullable=True)  # Frequently asked questions
    concept_relationships_json = db.Column(db.Text, nullable=True)  # Concept relationship map
    difficulty_level = db.Column(db.String(20), nullable=True)  # introductory/intermediate/advanced
    estimated_study_time = db.Column(db.String(50), nullable=True)  # e.g., "2 hours"
    short_summary = db.Column(db.Text, nullable=True)  # 1-2 sentence overview for card display
    
    def __repr__(self):
        return f'<Content {self.id}: {self.filename}>'
    
    # ── JSON property helpers ──
    
    @property
    def key_points(self) -> List[str]:
        """Get key points as a list."""
        return json.loads(self.key_points_json) if self.key_points_json else []
    
    @key_points.setter
    def key_points(self, value: Optional[List[str]]) -> None:
        """Set key points from a list."""
        self.key_points_json = json.dumps(value) if value else None
    
    @property
    def topics(self) -> List[str]:
        """Get topics as a list."""
        return json.loads(self.topics_json) if self.topics_json else []
    
    @topics.setter
    def topics(self, value: Optional[List[str]]) -> None:
        """Set topics from a list."""
        self.topics_json = json.dumps(value) if value else None
    
    @property
    def document_summary(self) -> dict:
        """Get the full structured document summary."""
        return json.loads(self.document_summary_json) if self.document_summary_json else {}
    
    @document_summary.setter
    def document_summary(self, value: Optional[dict]) -> None:
        """Set the full structured document summary."""
        self.document_summary_json = json.dumps(value) if value else None
    
    @property
    def sections(self) -> List[dict]:
        """Get sections as a list of dicts for citation mapping."""
        return json.loads(self.sections_json) if self.sections_json else []
    
    @sections.setter
    def sections(self, value: Optional[List[dict]]) -> None:
        """Set sections from a list of dicts."""
        self.sections_json = json.dumps(value) if value else None
    
    @property
    def learning_objectives(self) -> List[str]:
        """Get learning objectives."""
        return json.loads(self.learning_objectives_json) if self.learning_objectives_json else []
    
    @learning_objectives.setter
    def learning_objectives(self, value: Optional[List[str]]) -> None:
        self.learning_objectives_json = json.dumps(value) if value else None
    
    @property
    def discussion_topics(self) -> List[dict]:
        """Get discussion topics."""
        return json.loads(self.discussion_topics_json) if self.discussion_topics_json else []
    
    @discussion_topics.setter
    def discussion_topics(self, value: Optional[list]) -> None:
        self.discussion_topics_json = json.dumps(value) if value else None
    
    @property
    def important_terms(self) -> List[dict]:
        """Get important terms/vocabulary."""
        return json.loads(self.important_terms_json) if self.important_terms_json else []
    
    @important_terms.setter
    def important_terms(self, value: Optional[list]) -> None:
        self.important_terms_json = json.dumps(value) if value else None
    
    @property
    def faq(self) -> List[dict]:
        """Get frequently asked questions."""
        return json.loads(self.faq_json) if self.faq_json else []
    
    @faq.setter
    def faq(self, value: Optional[list]) -> None:
        self.faq_json = json.dumps(value) if value else None
    
    @property
    def concept_relationships(self) -> List[dict]:
        """Get concept relationships."""
        return json.loads(self.concept_relationships_json) if self.concept_relationships_json else []
    
    @concept_relationships.setter
    def concept_relationships(self, value: Optional[list]) -> None:
        self.concept_relationships_json = json.dumps(value) if value else None
    
    def get_summary_card(self) -> dict:
        """Get a compact summary for card display and AI context injection."""
        clean_name = self.filename.rsplit('.', 1)[0] if '.' in self.filename else self.filename
        clean_topic = clean_name.replace('_', ' ').replace('-', ' ').strip() or self.filename
        
        disallowed = {"vision analysis unavailable.", "processing failed", "uploaded content", "fallback mode active"}
        title = self.title or clean_topic
        if title.strip().lower() in disallowed or "unavailable" in title.lower():
            title = clean_topic

        summary = self.summary or ''
        if not summary or summary.strip().lower() in disallowed or "unavailable" in summary.lower():
            summary = f"Study material for {title}. Indexed and ready for Socratic tutoring with Knowri."

        short_summary = self.short_summary or (summary[:200] + '...' if len(summary) > 200 else summary)
        if short_summary.strip().lower() in disallowed or "unavailable" in short_summary.lower():
            short_summary = f"Study material: {title}. Ready for tutoring."

        return {
            'id': self.id,
            'filename': self.filename,
            'title': title,
            'summary': summary,
            'shortSummary': short_summary,
            'extractedText': self.extracted_text or '',
            'keyPoints': self.key_points or [f"Core principles of {title}", "Ready for Socratic tutoring"],
            'topics': self.topics or [title, self.content_type.capitalize()],
            'fileType': self.content_type,
            'difficultyLevel': self.difficulty_level or 'intermediate',
            'estimatedStudyTime': self.estimated_study_time or '45 mins',
            'topicCount': len(self.topics) if self.topics else 1,
            'conceptCount': len(self.document_summary.get('keyConcepts', [])) if self.document_summary else 0,
            'processingStatus': self.processing_status,
        }
    
    def get_full_summary(self) -> dict:
        """Get the complete structured document summary."""
        return {
            'id': self.id,
            'filename': self.filename,
            'title': self.title or self.filename,
            'fileType': self.content_type,
            'executiveSummary': self.document_summary.get('executiveSummary', self.summary or ''),
            'shortSummary': self.short_summary or '',
            'keyConcepts': self.document_summary.get('keyConcepts', []),
            'importantTerms': self.important_terms,
            'learningObjectives': self.learning_objectives,
            'discussionTopics': self.discussion_topics,
            'faq': self.faq,
            'sections': self.sections,
            'conceptRelationships': self.concept_relationships,
            'difficultyLevel': self.difficulty_level,
            'estimatedStudyTime': self.estimated_study_time,
            'topics': self.topics,
            'keyPoints': self.key_points,
            'processingStatus': self.processing_status,
            'createdAt': self.created_at.isoformat() if self.created_at else None,
        }
    
    def to_dict(self) -> dict:
        """Convert content to dictionary for API responses."""
        return {
            'id': self.id,
            'user_id': self.user_id,
            'filename': self.filename,
            'content_type': self.content_type,
            'file_path': self.file_path,
            'file_size': self.file_size,
            'title': self.title,
            'summary': self.summary,
            'short_summary': self.short_summary,
            'extracted_text': self.extracted_text,
            'key_points': self.key_points,
            'topics': self.topics,
            'document_summary': self.document_summary,
            'learning_objectives': self.learning_objectives,
            'difficulty_level': self.difficulty_level,
            'estimated_study_time': self.estimated_study_time,
            'processing_status': self.processing_status,
            'created_at': self.created_at.isoformat() if self.created_at else None
        }
    
    @classmethod
    def from_dict(cls, data: dict) -> 'Content':
        """Create a Content instance from a dictionary."""
        content = cls(
            id=data.get('id', str(uuid.uuid4())),
            user_id=data['user_id'],
            filename=data['filename'],
            content_type=data['content_type'],
            file_path=data['file_path'],
            file_size=data.get('file_size', 0),
            title=data.get('title'),
            summary=data.get('summary'),
            short_summary=data.get('short_summary'),
            difficulty_level=data.get('difficulty_level'),
            estimated_study_time=data.get('estimated_study_time'),
            processing_status=data.get('processing_status', 'pending'),
            created_at=datetime.fromisoformat(data['created_at']) if data.get('created_at') else datetime.utcnow()
        )
        # Set JSON properties through setters
        content.key_points = data.get('key_points', [])
        content.topics = data.get('topics', [])
        return content


# Allowed file types for upload
ALLOWED_FILE_TYPES = {'video', 'pdf', 'document', 'presentation', 'text', 'image'}

# Allowed file extensions mapped to file types
ALLOWED_EXTENSIONS = {
    # Video extensions
    '.mp4': 'video',
    '.avi': 'video',
    '.mov': 'video',
    '.mkv': 'video',
    '.webm': 'video',
    # PDF extension
    '.pdf': 'pdf',
    # Document extensions
    '.docx': 'document',
    '.doc': 'document',
    # Presentation extensions
    '.pptx': 'presentation',
    '.ppt': 'presentation',
    # Text extensions
    '.txt': 'text',
    # Image extensions
    '.png': 'image',
    '.jpg': 'image',
    '.jpeg': 'image',
    '.gif': 'image',
    '.webp': 'image',
    '.bmp': 'image',
}


def get_file_type(filename: str) -> Optional[str]:
    """
    Get the file type based on filename extension.
    
    Args:
        filename: The filename to check.
        
    Returns:
        'video', 'pdf', 'document', 'presentation', 'text', 'image', or None if not allowed.
    """
    if not filename:
        return None
    
    ext = '.' + filename.rsplit('.', 1)[-1].lower() if '.' in filename else ''
    return ALLOWED_EXTENSIONS.get(ext)


def is_allowed_file(filename: str) -> bool:
    """Check if a file is allowed based on its extension."""
    return get_file_type(filename) is not None
